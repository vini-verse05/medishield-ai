"""Repeats the whole experiment (generate -> train -> evaluate) with several
random seeds and reports mean and standard deviation. A single run can be lucky
or unlucky; this shows how stable the results are. Data is still synthetic.

Run:  python -m ml.evaluate_multiseed [--seeds 5] [--first-seed 100]
"""
import argparse
import json
import os
import time

import numpy as np

from ml import settings
from ml.detector import Detector
from ml.evaluate import fmt, label_features, md_table, run_evaluation
from ml.features import extract_features
from ml.generate_data import generate
from ml.train import fit_bundle

PER_ROLE_KEYS = {"precision": "precision", "recall": "recall", "f1": "f1",
                 "fpr": "fpr", "roc_auc": "roc_auc_pooled_margin"}
GLOBAL_KEYS = {"precision": "precision", "recall": "recall", "f1": "f1",
               "fpr": "fpr", "roc_auc": "roc_auc"}
PREVALENCES = [0.01, 0.03, 0.08]


def mean_std(values):
    vals = [v for v in values if v is not None]
    if not vals:
        return {"mean": None, "std": None, "n": 0}
    return {"mean": float(np.mean(vals)), "std": float(np.std(vals, ddof=0)), "n": len(vals)}


def aggregate_runs(results):
    """Combine the dictionaries returned by ml.evaluate.run_evaluation."""
    per_role = {name: mean_std([r["overall"][key] for r in results])
                for name, key in PER_ROLE_KEYS.items()}
    baseline = {name: mean_std([r["global_baseline_no_roles"][key] for r in results])
                for name, key in GLOBAL_KEYS.items()}

    scenarios = {}
    for r in results:
        for name, m in r["by_scenario"].items():
            s = scenarios.setdefault(name, {"n": 0, "detected": 0})
            s["n"] += m["n"]
            s["detected"] += m["detected"]
    for s in scenarios.values():
        s["recall"] = s["detected"] / s["n"] if s["n"] else None

    # Derived, not measured: precision = r*p / (r*p + fpr*(1-p)) for anomaly
    # prevalence p, assuming the measured mean recall and FPR stay the same.
    rec, fpr = per_role["recall"]["mean"], per_role["fpr"]["mean"]
    projected = []
    for p in PREVALENCES:
        denom = rec * p + fpr * (1 - p)
        projected.append({"prevalence": p, "precision": rec * p / denom if denom > 0 else None})

    return {"n_runs": len(results), "per_role_models": per_role,
            "global_baseline": baseline, "recall_by_scenario": scenarios,
            "projected_precision": projected}


def pm(m):
    return "n/a" if m["mean"] is None else f"{m['mean']:.3f} ± {m['std']:.3f}"


def render_markdown(agg, seeds):
    names = ["precision", "recall", "f1", "fpr", "roc_auc"]
    out = ["# MediShield AI: multi-seed evaluation", "",
           f"Generated by `python -m ml.evaluate_multiseed`: {agg['n_runs']} independent runs "
           f"(seeds {seeds}). Each run generates new synthetic data, trains, and is "
           "evaluated on its own held-out test period. Values are mean ± standard deviation. "
           "Synthetic data: these figures do not predict real-world performance.", "",
           "## Per-role models vs one global model", "",
           md_table(["Model"] + names,
                    [["Per-role Isolation Forests"] + [pm(agg["per_role_models"][n]) for n in names],
                     ["Global model (no roles)"] + [pm(agg["global_baseline"][n]) for n in names]]),
           "", "## Recall by scenario (pooled over all runs)", "",
           md_table(["Scenario", "Anomalous days", "Detected", "Recall"],
                    [[s, m["n"], m["detected"], fmt(m["recall"])]
                     for s, m in agg["recall_by_scenario"].items()]), "",
           "## Projected precision at lower anomaly prevalence (derived)", "",
           "Computed as `r*p / (r*p + FPR*(1-p))` from the mean recall `r` and mean FPR above, "
           "assuming both stay constant when the share `p` of anomalous user-days changes. "
           "It is arithmetic, not a separate measurement.", "",
           md_table(["Anomalous share of user-days", "Projected precision"],
                    [[f"{p['prevalence']:.0%}", fmt(p["precision"])]
                     for p in agg["projected_precision"]]), ""]
    return "\n".join(out)


def run(seeds):
    results = []
    for seed in seeds:
        start = time.time()
        events, labels, _ = generate(seed=seed)
        labeled = label_features(extract_features(events), labels)
        detector = Detector(fit_bundle(labeled[labeled["split"] == "train"], seed=seed))
        results.append(run_evaluation(events, labels, detector))
        print(f"  seed {seed}: done in {time.time() - start:.0f}s")
    return results


def main():
    parser = argparse.ArgumentParser(description="Multi-seed evaluation.")
    parser.add_argument("--seeds", type=int, default=5, help="number of runs")
    parser.add_argument("--first-seed", type=int, default=100)
    args = parser.parse_args()
    if args.seeds < 2:
        parser.error("--seeds must be at least 2")

    seeds = list(range(args.first_seed, args.first_seed + args.seeds))
    print(f"Running {len(seeds)} experiments (this takes a few minutes)...")
    agg = aggregate_runs(run(seeds))

    os.makedirs(settings.REPORT_DIR, exist_ok=True)
    with open(os.path.join(settings.REPORT_DIR, "evaluation_multiseed.json"), "w",
              encoding="utf-8") as f:
        json.dump({"seeds": seeds, **agg}, f, indent=2)
    text = render_markdown(agg, seeds)
    with open(os.path.join(settings.REPORT_DIR, "evaluation_multiseed.md"), "w",
              encoding="utf-8") as f:
        f.write(text)
    print()
    print(text)
    print(f"Reports written to {settings.REPORT_DIR}")


if __name__ == "__main__":
    main()