"""Runs every test script in its own process and writes docs/TEST_RESULTS.md
with the actual results of THIS run on THIS machine. Nothing is pre-filled.

Run:  python run_all_tests.py
"""
import os
import platform
import re
import subprocess
import sys
import time
from datetime import datetime, timezone
from importlib import metadata

ROOT = os.path.dirname(os.path.abspath(__file__))
RESULTS_PATH = os.path.join(ROOT, "docs", "TEST_RESULTS.md")
SCRIPTS = ["test_db.py", "test_auth.py", "test_ehr.py", "test_ml.py",
           "test_alerts.py", "test_dashboard.py", "test_scenarios.py"]
PACKAGES = ["Flask", "Werkzeug", "pandas", "numpy", "scikit-learn"]


def run_script(name):
    start = time.time()
    proc = subprocess.run(
        [sys.executable, name], cwd=ROOT, capture_output=True, text=True,
        encoding="utf-8", errors="replace",
        env={**os.environ, "PYTHONIOENCODING": "utf-8"})
    output = (proc.stdout or "") + (proc.stderr or "")
    match = re.search(r"All (\d+) checks passed", proc.stdout or "")
    return {
        "script": name,
        "ok": proc.returncode == 0 and match is not None,
        "checks": int(match.group(1)) if match else None,
        "seconds": time.time() - start,
        "failed": next((ln.strip() for ln in output.splitlines()
                        if ln.startswith("AssertionError: FAILED:")), None),
        "tail": "\n".join(output.strip().splitlines()[-15:]),
    }


def versions():
    out = {"Python": platform.python_version(), "Platform": platform.platform()}
    for pkg in PACKAGES:
        try:
            out[pkg] = metadata.version(pkg)
        except metadata.PackageNotFoundError:
            out[pkg] = "not installed"
    return out


def write_markdown(results, env):
    stamp = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    lines = ["# MediShield AI: test results", "",
             f"Generated by `python run_all_tests.py` on {stamp}. These are the actual "
             "results of that run.", "", "## Environment", ""]
    lines += [f"- {k}: {v}" for k, v in env.items()]
    lines += ["", "## Results", "", "| Script | Result | Checks passed | Seconds |", "|---|---|---|---|"]
    for r in results:
        checks = r["checks"] if r["checks"] is not None else "-"
        lines.append(f"| {r['script']} | {'PASS' if r['ok'] else 'FAIL'} | {checks} | {r['seconds']:.0f} |")
    total = sum(r["checks"] or 0 for r in results)
    lines += ["", f"Total checks passed: {total}", ""]
    for r in results:
        if not r["ok"]:
            lines += [f"## Failure: {r['script']}", "", f"First failing check: {r['failed'] or 'see output'}",
                      "", "```", r["tail"], "```", ""]
    os.makedirs(os.path.dirname(RESULTS_PATH), exist_ok=True)
    with open(RESULTS_PATH, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))


def main():
    print("Running all test scripts. Model-based tests take a short while.\n")
    results = []
    for name in SCRIPTS:
        print(f"  running {name} ...", flush=True)
        r = run_script(name)
        results.append(r)
        status = "PASS" if r["ok"] else "FAIL"
        extra = f"{r['checks']} checks" if r["ok"] else (r["failed"] or "see docs/TEST_RESULTS.md")
        print(f"    {status}  ({r['seconds']:.0f}s)  {extra}")
    write_markdown(results, versions())
    failed = [r["script"] for r in results if not r["ok"]]
    print(f"\nWrote {RESULTS_PATH}")
    if failed:
        print("FAILED: " + ", ".join(failed))
        sys.exit(1)
    print(f"All {len(results)} test scripts passed.")


if __name__ == "__main__":
    main()